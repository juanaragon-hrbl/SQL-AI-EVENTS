CREATE VIEW [dbo].[v_EventTickets_VM]
	AS 
SELECT          ETR.PK_DISTRIBUTOR2 PK_DISTRIBUTOR2,
                MAX(ETR.DistributorId2) DISTRIBUTORID2,
				ETR.PK_EVENT,
		        CONVERT(DATETIME,LEFT(CONVERT(VARCHAR(10),F.ROYALTYMONTH,112),6)+'01',112) as  VOLUMEMONTH,
				SUM(F.PPV)  DSPPV,
				SUM(ISNULL(F.SP_TV,0) + ISNULL(F.SP_MainTV,0)) DSTV,
				SUM(F.DLV)  DSDLV,
				SUM(ISNULL(F.RO,0) + ISNULL(F.MainRO,0)) DSRO,
				SUM(F.PB)  DSPB,
				SUM(F.SP_PV) DSPV,
				SUM(F.SP_GV) DSGV
FROM (SELECT PK_DISTRIBUTOR2, DistributorId2, PK_Event, COUNT(*)   Cnt 
		      FROM dbo.v_EventTickets WITH(NOLOCK)
			  GROUP BY PK_DISTRIBUTOR2, DistributorId2, PK_Event) ETR
LEFT OUTER JOIN PubEvents.dbo.aggDSFinancial F WITH(NOLOCK) ON F.PK_Distributor = ETR.PK_Distributor2 	
GROUP BY PK_DISTRIBUTOR2,
         PK_EVENT,
         ROYALTYMONTH